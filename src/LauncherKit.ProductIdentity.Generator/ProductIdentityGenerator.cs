using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;

namespace LauncherKit.ProductIdentity.Generator;

/// <summary>
/// Emits <c>ProductIdentity</c> (one constant per identity value and <c>CreateOptions()</c> building
/// <c>LauncherProductOptions</c>) from the consumer's <c>Launcher*</c> MSBuild properties, which
/// <c>LauncherKit.Product.props</c> makes visible to the compiler. A missing or blank property fails the build.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ProductIdentityGenerator : IIncrementalGenerator
{
	/// <summary>The MSBuild property naming the namespace of the generated class.</summary>
	public const string NamespaceProperty = "LauncherProductNamespace";

	/// <summary>
	/// The <c>LauncherProductOptions</c> properties, each set from the MSBuild property of the same name prefixed with
	/// <c>Launcher</c>. Keep in sync with <c>LauncherKit.Product.props</c>.
	/// </summary>
	public static readonly IReadOnlyList<string> OptionNames =
	[
		"SkyrimDataDirectoryName",
		"LocalDatabaseFileName",
		"OAuthTokenEntropy",
		"EnvironmentVariablePrefix",
		"AppExecutableName",
		"DisplayName",
		"UserAgentProduct",
		"ModOrganizerDirectoryName",
		"ModpackProfileName",
		"ModpackVersionFile",
		"UserModsSeparator",
		"RequiredSkyrimVersion",
		"RegistryKey",
	];

	private const string ModpackVersionFile = "ModpackVersionFile";

	private static readonly DiagnosticDescriptor MissingProperty = new(
		"LKPI001",
		"Missing product property",
		"MSBuild property '{0}' is required to generate the product identity",
		"LauncherKit.ProductIdentity",
		DiagnosticSeverity.Error,
		isEnabledByDefault: true);

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		// Strings only, so the incremental pipeline compares the result by value.
		var identity = context.AnalyzerConfigOptionsProvider.Select(static (provider, _) => Generate(provider.GlobalOptions));
		context.RegisterSourceOutput(identity, static (output, result) =>
		{
			if (result.Missing.Length > 0)
			{
				foreach (var property in result.Missing.Split(';'))
				{
					output.ReportDiagnostic(Diagnostic.Create(MissingProperty, Location.None, property));
				}

				return;
			}

			output.AddSource("ProductIdentity.g.cs", SourceText.From(result.Source, Encoding.UTF8));
		});
	}

	internal static (string Source, string Missing) Generate(AnalyzerConfigOptions options)
	{
		var missing = new List<string>();
		var @namespace = Read(options, NamespaceProperty, missing);
		var values = OptionNames.Select(name => (Name: name, Value: Read(options, "Launcher" + name, missing))).ToList();
		if (missing.Count > 0)
		{
			return (string.Empty, string.Join(";", missing));
		}

		var source = new StringBuilder()
			.AppendLine("// <auto-generated/>")
			.AppendLine("#nullable enable")
			.AppendLine()
			.Append("namespace ").Append(@namespace).AppendLine(";")
			.AppendLine()
			.AppendLine("/// <summary>The product identity generated by LauncherKit from the Launcher* MSBuild properties.</summary>")
			.AppendLine("public static class ProductIdentity")
			.AppendLine("{");
		foreach (var (name, value) in values)
		{
			source.Append("\tpublic const string ").Append(name).Append(" = @\"").Append(value.Replace("\"", "\"\"")).AppendLine("\";");
		}

		source
			.AppendLine()
			.AppendLine("\tpublic static global::LauncherKit.Infrastructure.LauncherProductOptions CreateOptions() => new()")
			.AppendLine("\t{");
		foreach (var (name, _) in values)
		{
			source.Append("\t\t").Append(name).Append(" = ").Append(name);
			// Written with '/' in MSBuild; the launcher combines it with OS paths.
			if (name == ModpackVersionFile)
			{
				source.Append(".Replace('/', global::System.IO.Path.DirectorySeparatorChar)");
			}

			source.AppendLine(",");
		}

		source.AppendLine("\t};").AppendLine("}");
		return (source.ToString(), string.Empty);
	}

	private static string Read(AnalyzerConfigOptions options, string property, List<string> missing)
	{
		if (options.TryGetValue("build_property." + property, out var value) && !string.IsNullOrWhiteSpace(value))
		{
			return value;
		}

		missing.Add(property);
		return string.Empty;
	}
}
